#!/usr/bin/env python3
"""Register the existing gateway profiles and initialize private Turnstone state."""
import json
import os
import secrets
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
DEFAULT = 'qwen3.8-flash-next-iq3_xxs'


def main():
    os.umask(0o077)
    data = ROOT / 'data'
    data.mkdir(exist_ok=True, mode=0o700)
    (ROOT / 'workspace').mkdir(exist_ok=True)
    (ROOT / 'logs').mkdir(exist_ok=True, mode=0o700)
    sys.path.insert(0, str(REPO / 'network'))
    from gateway import catalog
    from cryptography.fernet import Fernet
    secret_path = data / 'secrets.json'
    if not secret_path.exists():
        secret_path.write_text(json.dumps({
            'jwt': secrets.token_urlsafe(48),
            'encryption': Fernet.generate_key().decode(),
        }))
    private = json.loads(secret_path.read_text())
    quote = json.dumps
    lines = [
        '# Generated by configure.py; private bootstrap configuration.',
        '[database]', 'backend = "sqlite"', f'path = {quote(str(data / "turnstone.db"))}',
        '[auth]', f'jwt_secret = {quote(private["jwt"])}',
        '[security]', f'mcp_token_encryption_key = {quote(private["encryption"])}',
        '[model]', f'default = {quote(DEFAULT)}',
    ]
    models = catalog()
    for model in models.values():
        lines.extend([
            '', f'[models.{quote(model["id"])}]',
            f'model = {quote(model["id"])}', 'provider = "openai"',
            'base_url = "http://127.0.0.1:10000/v1"',
            'api_key = "${LOCAL_LLM_API_KEY}"',
            f'context_window = {model["context_length"]}',
            'max_concurrency = 1', 'max_tokens = 8192',
            f'[models.{quote(model["id"])}.capabilities]',
            'supports_vision = false', 'supports_web_search = false',
        ])
    config = data / 'config.toml'
    config.write_text('\n'.join(lines) + '\n')
    config.chmod(0o600)
    from turnstone.core.storage import init_storage
    from turnstone.core.config_store import ConfigStore
    from turnstone.core.auth import hash_password
    storage = init_storage(path=str(data / 'turnstone.db'))
    settings = ConfigStore(storage=storage, node_id='localuser-local')
    # Seed once so subsequent catalog refreshes preserve UI preferences.
    marker = data / 'initialized'
    if not marker.exists():
        for key, value in {
            'judge.enabled': False,
            'judge.cancel_on_approval': True,
            'model.default_alias': DEFAULT,
            'model.max_tokens': 8192,
            'session.compact_max_tokens': 4096,
            'session.auto_compact_pct': 0.8,
            'server.max_workstreams': 1,
            'tools.skip_permissions': False,
        }.items():
            settings.set(key, value, changed_by='local-install')
        marker.write_text('Initial local settings applied.\n')
    if storage.get_user_by_username('localuser') is None:
        password = secrets.token_urlsafe(24)
        user_id = uuid.uuid4().hex
        storage.create_user(user_id, 'localuser', 'localuser', hash_password(password))
        storage.assign_role(user_id, 'builtin-admin', '')
        (data / 'login.txt').write_text(
            'Turnstone: http://127.0.0.1:3081\nUsername: localuser\nPassword: ' + password + '\n'
        )
    print(f'Registered {len(models)} gateway profiles; default: {DEFAULT}.')
    print('Private login details:', data / 'login.txt')


if __name__ == '__main__':
    main()
